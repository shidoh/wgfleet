// AWGDSCPScrubChain names the chain that clears the DSCP field on packets leaving
// this node's AmneziaWG listen ports.
const AWGDSCPScrubChain = "awg_dscp_scrub"

// renderAWGDSCPScrub writes a chain that rewrites DSCP to CS0 and ECN to Not-ECT
// on every UDP packet this node sends from one of its AmneziaWG listen ports.
//
// The kernel AmneziaWG module marks handshake packets AF41 (TOS 0x88); the
// userspace implementation does not. On data packets the module carries only
// the inner packet's ECN bits to the outer header, not its DSCP (measured on the
// 3.1.20260906 build), so in practice the rule rewrites handshakes; it stays on
// data packets as well, in case a module build starts copying DSCP. A
// non-default DSCP on UDP from a VPN
// port is a free classifier feature for a middlebox, and it also tells the two
// implementations apart. CS0 is what almost all other UDP on the internet
// carries.
//
// Hooked on OUTPUT, not POSTROUTING: the tunnel's outer packets are generated by
// this host, so OUTPUT sees all of them, and it never sees FORWARDED traffic — an
// exit relaying a client's reply from some QUIC server's port 443 back into the
// tunnel must not have that inner packet matched just because the server port
// equals our listen port. The DSCP is already final at OUTPUT: the module writes
// it before handing the packet to the IP stack.
//
// Locally generated inner packets can still carry our port as their source (a
// resolver or proxy on this host answering a client over the tunnel), so the
// tunnel interfaces themselves are excluded: an outer packet never leaves through
// the tunnel it carries.
//
// Only egress is scrubbed. The DSCP a peer sends has already crossed the path by
// the time it reaches us; rewriting it on arrival hides nothing from anyone.
//
// The ECN bits are cleared too. The module sends each junk packet with a random
// TOS byte, so after the DSCP rewrite the two ECN bits are still random and flip
// between packets of one burst — no ordinary UDP sender does that, and a
// middlebox can key every handshake on it. Data packets carry the inner packet's
// ECN bits; clearing them only turns off ECN signalling through the tunnel, and
// the flow falls back to loss-based congestion control, as on most UDP.
//
// The `!=` guards keep the rules from rewriting (and re-checksumming) packets that
// are already clean, which is almost every packet from a userspace implementation.
func renderAWGDSCPScrub(b *strings.Builder, in RenderInput) {
	ports, ifaces := awgOwnedPortsAndIfaces(in)
	if len(ports) == 0 {
		return
	}
	match := fmt.Sprintf("oifname != %s udp sport %s", nftStrSet(ifaces), nftIntSet(ports))
	fmt.Fprintf(b, "\n\tchain %s {\n", AWGDSCPScrubChain)
	b.WriteString("\t\ttype filter hook output priority mangle; policy accept;\n")
	fmt.Fprintf(b, "\t\t%s ip dscp != cs0 ip dscp set cs0\n", match)
	fmt.Fprintf(b, "\t\t%s ip6 dscp != cs0 ip6 dscp set cs0\n", match)
	fmt.Fprintf(b, "\t\t%s ip ecn != not-ect ip ecn set not-ect\n", match)
	fmt.Fprintf(b, "\t\t%s ip6 ecn != not-ect ip6 ecn set not-ect\n", match)
	b.WriteString("\t}\n")
}

// awgOwnedPortsAndIfaces lists the AmneziaWG listen ports this node owns and the
// interfaces behind them.
//
// Exit: the master↔exit interface (Firewall.WGPort) and, when present, the
// lifeline interface (Firewall.LifelinePort). The exit-initiated flow needs no
// extra match: the exit dials the master FROM its interface's listen port, so the
// knock and everything after it already match by source port.
//
// Master: the client-facing interface (Firewall.WGPort is its listen port). The
// master's ends of the master↔exit tunnels live in userspace, which never sets
// DSCP, so they are left out.
func awgOwnedPortsAndIfaces(in RenderInput) (ports []int, ifaces []string) {
	switch in.Role {
	case domain.RoleExit:
		wg := in.WGInterface
		if wg == "" {
			wg = "awg0"
		}
		ports = []int{in.Firewall.WGPort}
		ifaces = []string{wg}
		if in.Firewall.LifelinePort > 0 {
			ports = append(ports, in.Firewall.LifelinePort)
			ifaces = append(ifaces, lifelineIfaceName(in))
		}
	case domain.RoleMaster:
		client := in.RedirInterface
		if client == "" {
			client = "wg0"
		}
		ports = []int{in.Firewall.WGPort}
		ifaces = []string{client}
	default:
		return nil, nil
	}
	ports = normalizePorts(ports)
	ifaces = dedupeSorted(ifaces)
	return ports, ifaces
}

func dedupeSorted(in []string) []string {
	out := append([]string(nil), in...)
	sort.Strings(out)
	n := 0
	for i, s := range out {
		if i > 0 && s == out[n-1] {
			continue
		}
		out[n] = s
		n++
	}
	return out[:n]
}

// nftIntSet renders one port bare and several as an anonymous set.
func nftIntSet(ports []int) string {
	if len(ports) == 1 {
		return fmt.Sprint(ports[0])
	}
	parts := make([]string, len(ports))
	for i, p := range ports {
		parts[i] = fmt.Sprint(p)
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// nftStrSet renders one quoted name bare and several as an anonymous set.
func nftStrSet(names []string) string {
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = fmt.Sprintf("%q", n)
	}
	if len(quoted) == 1 {
		return quoted[0]
	}
	return "{ " + strings.Join(quoted, ", ") + " }"
}
